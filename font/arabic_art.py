# -*- coding: utf-8 -*-
"""
Arabic font for Breath of Fire (GBA) - USA ROM.

Font architecture (verified in ROM):
  small font (8x8)  : base 0x22FA68, glyph(c) = base + (c-0x20)*32
  large font (8x16) : base 0x231668, top tile  = base + (c-0x20)*32
                                      bottom    = base + 0x1C00 + (c-0x20)*32
  Encoding: codes >= 0x80 are free (kana/kanji ranges unused in USA ROM).

Glyph forms (standard Arabic):
  ISO  isolated   - no connections
  INIT initial    - connects to the following letter (left side of cell)
  MEDI medial     - connects both sides
  FIN  final      - conners to the preceding letter (right side of cell)

Visual note: text is stored in VISUAL order (reversed), so the engine's
left-to-right printing yields correct right-to-left Arabic.
"""

